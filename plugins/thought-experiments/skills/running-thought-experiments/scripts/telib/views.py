from __future__ import annotations

from . import core

LABELS = {
    "en": {"question": "Question", "goal": "Goal", "terms": "Terms", "mode": "Mode", "flaw": "Setup flaw",
           "rivals": "Rivals", "status": "Status", "operations": "Operations", "attacks": "Attacks",
           "conclusion": "Conclusion", "premises": "Premises", "options": "Options", "score": "Prediction score",
           "reviews": "Review", "corrections": "Corrections", "sources": "Sources", "decisions": "User decisions",
           "generated": "Generated by te render. Do not edit by hand; edit events.jsonl through te add.",
           "next": "Next moves", "state": "State"},
    "ja": {"question": "問い", "goal": "ゴール", "terms": "用語", "mode": "モード", "flaw": "設定の欠陥",
           "rivals": "対立仮説", "status": "状態", "operations": "操作", "attacks": "攻撃",
           "conclusion": "結論", "premises": "前提", "options": "選択肢", "score": "予想の採点",
           "reviews": "事後評価", "corrections": "訂正", "sources": "出典", "decisions": "ユーザーの判断",
           "generated": "te render が生成した。手で編集せず、te add で events.jsonl に書く。",
           "next": "次の進め方", "state": "状態"},
}


def brief(state: dict, lens: dict) -> str:
    """Reviewer brief. Projects only question, terms, claim and labelled premises: the history,
    eliminated rivals and the author's own attacks are left out by construction, because each of
    them tells a reviewer where not to look."""
    f = state["frame"] or {}
    c = state["conclusion"]
    lines = ["# Review request", "", f"**Your lens:** {lens['text']}", "",
             "## Question", "", f.get("question", "(not framed yet)"), ""]
    if f.get("terms"):
        lines += ["## Terms (the reading the author took)", ""]
        lines += [f"- **{t['term']}**: {t['reading']}" for t in f["terms"]]
        lines.append("")
    if c:
        lines += ["## Claim", "", c.get("claim") or c["answer"], "", "## Premises", ""]
        for p in c["premises"]:
            lines.append(f"- {p['pid']} [{p['label']}] {p['text']}")
        lines.append("")
    else:
        live = [r for r in state["rivals"].values() if r["status"] != "eliminated"]
        lines += ["## Candidate answers", ""] + [f"- {r['rid']}: {r['text']}" for r in live] + [""]
    lines += [
        "## What to return", "",
        "1. Your strongest objections. For each, name its target (premise, inference or conclusion) and the premise id if any, and give your confidence (low, medium, high).",
        "2. At least one counter thought experiment.",
        "3. A better-supported rival answer, if you have one.",
        "4. For every fact you rely on, say whether you checked it in a primary source (the authors' own publication or the issuing body's document; give URL and page) or recalled it.",
        "",
    ]
    return "\n".join(lines)


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return out


def render(state: dict, sources: dict, lang: str = "en", scored: dict | None = None) -> str:
    L = LABELS[lang]
    f = state["frame"] or {}
    exp = state["experiment"]
    lines = [f"# {f.get('question', exp.get('id', 'experiment'))}", "", f"<!-- {L['generated']} -->", ""]
    if f:
        lines += [f"- **{L['goal']}:** {f['goal']}",
                  f"- **{L['mode']}:** {f['mode'] if isinstance(f['mode'], str) else ', '.join(f['mode'])}",
                  f"- **{L['status']}:** {state['closed'] or 'open'}", ""]
        lines += [f"## {L['terms']}", ""] + [f"- **{t['term']}**: {t['reading']}" for t in f["terms"]] + [""]
        lines += [f"## {L['flaw']}", "", f["flaw"], ""]
    if state["rivals"]:
        lines += [f"## {L['rivals']}", ""]
        lines += _table(["id", L["rivals"], L["status"], "would_reject_if"],
                        [[r["rid"] + (" (opposite)" if r["is_opposite"] else ""), r["text"], r["status"], r["would_reject_if"]]
                         for r in state["rivals"].values()])
        lines.append("")
    ops = state["probes"] + state["operations"]
    if ops:
        lines += [f"## {L['operations']}", ""]
        for e in sorted(ops, key=lambda e: e["id"]):
            verdicts = ", ".join(f"{k}: {v['status']}" for k, v in e["verdicts"].items())
            lines += [f"### {e['kind']} {e['id']}: {', '.join(e['varied'])}", "", e["result"], "", f"*{verdicts}*", ""]
    if state["attacks"]:
        lines += [f"## {L['attacks']}", ""]
        for e in state["attacks"]:
            lines += [f"### {e['id']}: {e['reviewer']} / {e['lens']}", ""]
            for o in e["objections"]:
                lines.append(f"- [{o['target']}] {o['text']} → {o.get('response', '—')}: {o.get('reason', '')}")
            lines.append("")
    c = state["conclusion"]
    if c:
        lines += [f"## {L['conclusion']}", "", c["answer"], ""]
        if c.get("claim"):
            lines += [f"> {c['claim']}", ""]
        lines += [f"### {L['premises']}", ""]
        lines += _table(["id", L["premises"], "label", "if_false", L["sources"]],
                        [[p["pid"], p["text"], p["label"], p.get("if_false", ""),
                          ", ".join(f"{x['source']} ({x['level']})" for x in p.get("citations", []))] for p in c["premises"]])
        lines.append("")
        if c.get("options"):
            lines += [f"### {L['options']}", ""]
            lines += _table(["id", L["options"], L["status"], ""], [[o["oid"], o["text"], o["status"], o.get("reason", "")] for o in c["options"]])
            lines.append("")
    if scored:
        lines += [f"## {L['score']}", "", f"Brier {scored['brier']} (p = {scored['p_answer']} on {scored['answer_rival']}, by {scored['by_whom']})", ""]
    if state["reviews"]:
        lines += [f"## {L['reviews']}", ""] + [f"- {e['by_whom']}: {e['text']}" for e in state["reviews"]] + [""]
    if state["decisions"]:
        lines += [f"## {L['decisions']}", ""] + [f"- {e['what']}" for e in state["decisions"]] + [""]
    if state["corrections"]:
        lines += [f"## {L['corrections']}", ""]
        for key, evs in sorted(state["corrections"].items()):
            lines += [f"- {key}: {e['what']} ({e['why']})" for e in evs]
        lines.append("")
    if sources:
        lines += [f"## {L['sources']}", ""]
        for sid, s in sorted(sources.items()):
            sha = (s.get("sha256") or "")[:12]
            lines.append(f"- **{sid}** {s.get('title', '')} — {s.get('url', s.get('obtained'))} ({s.get('obtained')}{', sha256 ' + sha if sha else ''})")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def argdown(state: dict) -> str:
    """Rivals, premises, the conclusion and objections in Argdown syntax (argdown.org)."""
    out = ["# " + ((state["frame"] or {}).get("question", "experiment")), ""]
    for r in state["rivals"].values():
        tag = " #eliminated" if r["status"] == "eliminated" else ""
        out.append(f"[{r['rid']}]: {r['text']}{tag}")
    c = state["conclusion"]
    if c:
        out += ["", "<Conclusion>", ""]
        for i, p in enumerate(c["premises"], 1):
            out.append(f"({i}) [{p['pid']}]: {p['text']} #{p['label']}")
        out += ["----", f"({len(c['premises']) + 1}) {c['answer']}"]
        if c.get("answer_rival"):
            out += ["", f"<Conclusion>", f"  +> [{c['answer_rival']}]"]
        for e in state["attacks"]:
            for j, o in enumerate(e["objections"], 1):
                out += ["", f"<Objection {e['id']}.{j}>: {o['text']} #{o['target']}", "  -> <Conclusion>"]
    return "\n".join(out) + "\n"


def reply_skeleton(state: dict, step: dict, scored: dict | None, lang: str = "en") -> str:
    """The fixed tail of a reply: state lines and the next-move slots, so its shape never drifts."""
    L = LABELS[lang]
    rivals = ", ".join(f"{r['rid']}={r['status']}" for r in state["rivals"].values()) or "-"
    lines = [f"**{L['state']}**", f"- stage: {step['stage']} ({step['name']})", f"- rivals: {rivals}"]
    if step["missing"]:
        lines.append(f"- missing: {'; '.join(m['message'] for m in step['missing'][:3])}")
    if scored:
        lines.append(f"- score: Brier {scored['brier']}")
    lines += ["", f"**{L['next']}**", "1. …", "2. …", "3. …", "4. …"]
    return "\n".join(lines) + "\n"


